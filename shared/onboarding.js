// The one prompt a new library starts with. Run in ChatGPT, Claude or Gemini, it asks the AI to find the
// prompts you reuse and write them as a Prolly import block (shared/importer.js reads it).
// It must contain no #variables#: picking it should send it straight away. test/importer.test.mjs checks.
(function () {
  'use strict';
  const PM = (globalThis.PM = globalThis.PM || {});
  if (PM.SETUP_PROMPT) return;

  PM.SETUP_PROMPT = {
    title: 'Set up my prompt library',
    folder: '',
    tags: ['setup'],
    text: [
      'I want to set up my prompt library in Prolly. Help me find the prompts I already reuse, clean them up, and organize them so I can import them in one step.\n',
      '\n',
      'STEP 1 — Gather my prompts. Use the first option that works:\n',
      'a) If you can search my past conversations, review my last ~100 chats or 3 months, whichever is smaller. Tell me how many you actually reviewed.\n',
      'b) If you can\'t, say so and ask me to paste 10–30 prompts I\'ve sent recently. Wait for them before going on.\n',
      'c) If I have no history, interview me in one short message: my role, the 3–5 tasks I use AI for most, and one prompt that worked really well. Wait for my answers.\n',
      '\n',
      'STEP 2 — Find the patterns. Look for:\n',
      '- Recurring tasks: the kinds of questions I ask again and again.\n',
      '- My prompting habits: phrasings, constraints or formats I add that make answers better (e.g. "give me pros and cons", "don\'t use tables", "ask me before assuming").\n',
      '- One-off gems: things I asked for only once that clearly improved the answer.\n',
      '- Weak spots: prompts where I left out context, had a wrong premise, or buried the real question.\n',
      'Back each pattern with a short quote from my prompts (under 20 words, with names and personal details removed).\n',
      '\n',
      'STEP 3 — Write the library.\n',
      '- Prompts: turn each recurring task into a reusable template. Each prompt states the context needed, the ask, and the output shape I like. Fix the weak spots you found.\n',
      '- Variables: replace the details that change each time with variables, written exactly the way Prolly reads them:\n',
      '  - A value: a hash sign, the variable\'s name, then a hash sign, e.g. "# audience #".\n',
      '  - Fixed choices: a hash sign, the name, a colon, the choices separated by vertical bars, then a hash sign, e.g. "# format:table|bullets|prose #". The first choice is the default.\n',
      '  - The spaces after the opening and before the closing hash sign in these examples are only there so this message isn\'t read as variables. Write yours with no spaces.\n',
      '  - Names use only letters, digits and underscores, start with a letter, and contain no spaces: target_audience, not "target audience". Every list of choices needs a name.\n',
      '  - Use the same name each time the same value appears in a prompt.\n',
      '- Modifiers: turn my habits and gems into short snippets I can add to any prompt.\n',
      '- Never put sensitive personal details (health, relationships, finances, names of people) into a template. Use a variable instead.\n',
      '\n',
      'STEP 4 — Organize.\n',
      '- Folders = the job a prompt does (e.g. Learn, Research & compare, Decide & plan, Build, Write). Each prompt goes in exactly one folder, 6–10 folders total. Name them after how I work, not generic categories.\n',
      '- Tags = cross-cutting traits: output (table, pros-cons), depth (quick, deep), language, context. 15 tags max, lowercase, words joined with hyphens.\n',
      '- Modifiers go in a folder called Modifiers.\n',
      '\n',
      'STEP 5 — Deliver, in this order:\n',
      '1. How I prompt, in 5 lines max: my common structure, my best habits, my most common weak spot.\n',
      '2. A ranked table with columns: Title | Folder | Why it\'s useful | Start here. Rank by usefulness (how often I\'d use it × how much typing it saves). Mark the top 5–10 as "start here". Put "maybe" items at the bottom.\n',
      '3. Three questions for me so we can refine the library together.\n',
      '4. LAST: the import block, following the rules below exactly.\n',
      '\n',
      'IMPORT BLOCK RULES\n',
      '- Output one block that opens with a line containing only ~~~~prolly and closes with a line containing only ~~~~. Don\'t use that fence anywhere else in your reply.\n',
      '- The first line inside the block is the header: prolly-import v1 | part 1 of 1\n',
      '- Then one entry per prompt or modifier, in ranked order:\n',
      '  === PROMPT ===\n',
      '  title: (2–6 words)\n',
      '  folder: (one folder name)\n',
      '  tags: (comma-separated)\n',
      '  start-here: (yes or no)\n',
      '  ---\n',
      '  (the full prompt text, exactly as I would send it, with its variables)\n',
      '- Modifiers use folder: Modifiers. Items you\'re unsure about get the tag maybe.\n',
      '- The last line before the closing fence is: === END ===\n',
      '- Never put ~~~~, or a line starting with ===, inside a prompt\'s text.\n',
      '- Put at most 15 prompts and 8 modifiers in one block. If there are more, output part 1 of N (update the header), end it with === END ===, and tell me to say "continue" for the next part. Every part has its own header and END line.\n',
      '- If we refine the library later, output the complete block again, not just the changes.\n',
      '- Right after the block, add this line for me: To import, click Review & import in the Prolly bar on this page, or copy the block and paste it in Prolly: Settings, Library, Import from AI.\n',
      '\n',
      'Example of one entry:\n',
      '~~~~prolly\n',
      'prolly-import v1 | part 1 of 1\n',
      '=== PROMPT ===\n',
      'title: Meeting notes to actions\n',
      'folder: Decide & plan\n',
      'tags: quick, list\n',
      'start-here: yes\n',
      '---\n',
      'Turn these meeting notes into a list of action items with an owner and due date for each. Flag anything without an owner. Notes:\n',
      '=== END ===\n',
      '~~~~\n',
      '\n',
      'Don\'t invent prompts I\'d never use. If you\'re unsure whether something is a pattern, include it with the tag maybe rather than leaving it out.'
    ].join('')
  };
})();
